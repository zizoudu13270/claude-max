MAP = load(DOCS / "RENAME_MAP.json")
TIER_LABEL = {
    "A": "named from an existing readable token",
    "B": "named from the single item family / player state that guards it",
    "C": "role not determinable - stable numbering",
}


def escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def short(text: str, limit: int = 90) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


def guard_summary(fact: dict) -> str:
    bits = []
    if fact["tags"]:
        bits.append("tags: " + ", ".join(fact["tags"][:4]))
    if fact["items"]:
        bits.append("items: " + ", ".join(fact["items"][:4]))
    states = [q for q in fact["queries"]
              if q.startswith("is_") or q in {"blocking", "vertical_speed", "ground_speed"}]
    if states:
        bits.append("queries: " + ", ".join(states[:4]))
    return short("; ".join(bits)) or "—"


def animation_index(facts: dict) -> str:
    """`facts` is keyed by the *new* identifiers, since it reads the packs as
    they are now; the rename map supplies the original name for each row."""
    anim_map = MAP["animations"]
    old_of = {new: old for old, new in anim_map.items()}
    rationale = MAP["animation_rationale"]
    alias_map = MAP["entity_animation_aliases"]

    tiers = collections.Counter(r["tier"] for r in rationale.values())
    lines = [
        f"# Animation index — {PROJECT_NAME}",
        "",
        f"Developer: **{STUDIO}**. Generated by `tools/baf/make_docs.py`; "
        "do not edit by hand.",
        "",
        f"{len(anim_map)} animations. Every one of them survived the refactor: "
        "`tools/baf/signature.py` reports identical shape digests "
        "(length, loop, bones, channels, keyframes, interpolation) before and after.",
        "",
        "How the **probable function** column was reached:",
        "",
    ]
    for tier in ("A", "B", "C"):
        lines.append(f"- **{tier}** — {TIER_LABEL[tier]} ({tiers[tier]} animations)")
    lines += [
        "",
        "Tier C animations keep a neutral `state_NNN` identifier on purpose: "
        "inventing a descriptive name for them would be a guess, and a wrong "
        "name is worse than a neutral one.",
        "",
        "| # | old id | new id | tier | probable function | controller · state | guard | loop | length | bones |",
        "|---|--------|--------|------|-------------------|--------------------|-------|------|--------|-------|",
    ]

    for index, new_id in enumerate(sorted(facts), start=1):
        old_id = old_of[new_id]
        fact = facts[new_id]
        why = rationale[old_id]
        contexts = []
        for context in fact["contexts"][:2]:
            contexts.append(f"`{context['controller'].split('.')[-1]}` · `{context['state']}`")
        if not contexts:
            contexts = ["played directly from `player.entity.json`"]
        elif len(fact["contexts"]) > 2:
            contexts.append(f"(+{len(fact['contexts']) - 2})")

        if why["tier"] == "C":
            function = "unknown"
        elif why["tier"] == "A":
            function = f"`{why['token']}` (from {why['source']})"
        else:
            function = f"relates to `{why['token']}` ({why['source']})"

        bones = ", ".join(fact["bones"][:3]) + ("…" if len(fact["bones"]) > 3 else "")
        lines.append(
            f"| {index} | `{old_id}` | `{new_id}` | {why['tier']} | "
            f"{escape(function)} | {escape(' '.join(contexts))} | "
            f"{escape(guard_summary(fact))} | {'yes' if fact['loop'] else 'no'} | "
            f"{fact['length'] if fact['length'] is not None else '—'} | "
            f"{fact['bone_count']}{f' ({escape(bones)})' if bones else ''} |"
        )

    lines += [
        "",
        "## Client-entity aliases",
        "",
        "`player.entity.json` addresses animations through short aliases. All of "
        f"them now carry the `lbr_` prefix ({len(alias_map)} aliases).",
        "",
        "| old alias | new alias | target |",
        "|-----------|-----------|--------|",
    ]
    entity = load(rp_paths()["entity"])["minecraft:client_entity"]["description"]
    for old_alias in sorted(alias_map):
        new_alias = alias_map[old_alias]
        lines.append(f"| `{old_alias}` | `{new_alias}` | `{entity['animations'][new_alias]}` |")
    return "\n".join(lines) + "\n"


def resource_usage() -> str:
    """Classify every shipped asset as USED, UNUSED_CONFIRMED or UNRESOLVED."""
    entity = load(rp_paths()["entity"])["minecraft:client_entity"]["description"]
    terrain = load(RP / "textures" / "terrain_texture.json")["texture_data"]

    referenced: set[str] = set(entity["textures"].values())

    def collect(value):
        if isinstance(value, str):
            referenced.add(value)
        elif isinstance(value, list):
            for item in value:
                collect(item)
        elif isinstance(value, dict):
            for key, item in value.items():
                if key != "weight":
                    collect(item)

    for body in terrain.values():
        collect(body["textures"])

    rows = []
    for path in sorted(RP.rglob("*.png")):
        stem = str(path.relative_to(RP).with_suffix("")).replace("\\", "/")
        if stem == "pack_icon":
            rows.append((rel(path), "USED", "pack icon, read by Minecraft directly"))
        elif stem in referenced:
            rows.append((rel(path), "USED", "referenced by path"))
        elif stem in {"textures/blocks/fern", "textures/blocks/tallgrass"}:
            rows.append((rel(path), "UNRESOLVED",
                         "sits on a vanilla texture path, so it replaces the vanilla "
                         "file for every vanilla atlas entry that points there; kept"))
        else:
            rows.append((rel(path), "UNUSED_CONFIRMED", "no reference found"))
    for path in sorted(BP.rglob("*.png")):
        rows.append((rel(path), "USED", "pack icon, read by Minecraft directly"))

    counts = collections.Counter(status for _, status, _ in rows)
    lines = [
        f"# Resource usage — {PROJECT_NAME}",
        "",
        "Generated by `tools/baf/make_docs.py`.",
        "",
        "Only `UNUSED_CONFIRMED` assets may be deleted automatically. "
        "`UNRESOLVED` assets are kept: the reference exists, it just cannot be "
        "proven from inside this add-on.",
        "",
        "| status | count |",
        "|--------|-------|",
    ]
    for status in ("USED", "UNRESOLVED", "UNUSED_CONFIRMED"):
        lines.append(f"| {status} | {counts[status]} |")
    lines += ["", "| file | status | reason |", "|------|--------|--------|"]
    for path, status, reason in rows:
        lines.append(f"| `{path}` | {status} | {reason} |")
    return "\n".join(lines) + "\n"


