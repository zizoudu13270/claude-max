def main() -> int:
    facts, _ = evidence()
    for name, body in (("ANIMATION_INDEX.md", animation_index(facts)),
                       ("RESOURCE_USAGE.md", resource_usage()),
                       ("PROJECT_AUDIT.md", project_audit(facts))):
        (DOCS / name).write_text(body, encoding="utf-8")
        print(f"wrote docs/baf/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
