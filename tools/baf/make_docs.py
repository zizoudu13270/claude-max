#!/usr/bin/env python3
"""Generate the provenance and audit documents for Better Animation & Feature.

Writes, under docs/baf/:
  ANIMATION_INDEX.md    one row per animation - old id, new id, probable
                        function, controller, guard, loop, length, bones
  PROJECT_AUDIT.md      what was analysed, what changed, what is unresolved
  RESOURCE_USAGE.md     USED / UNUSED_CONFIRMED / UNRESOLVED for every asset

AUTHORSHIP.md and THIRD_PARTY_REVIEW.md are written by hand - they are
statements about who made what, not generated facts.

Run:  python3 tools/baf/make_docs.py
"""
from __future__ import annotations

